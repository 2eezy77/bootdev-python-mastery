def sum(a,b,c,d):
    return a+b+c+d

def sub(c,d):
    return c-d

def product(a,b):
    return a*b

def quotient(c,d): 
    return c/d

def main():

    add_all = sum(15, 13, 12, 8)
    subtracting = sub(3, 5)
    multiply = product(3, 3)
    divide = quotient(3, 3)

    print(add_all)
    print(subtracting)
    print(multiply)
    print(divide)

main()